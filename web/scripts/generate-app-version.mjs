import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const webRoot = fileURLToPath(new URL('../', import.meta.url));
const outputDirectory = new URL('../src/app/core/generated/', import.meta.url);
const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));

// Git metadata is optional when building from a downloaded source archive.
let commit = 'unknown';
let dirty = false;
try {
  const git = (...args) => execFileSync('git', args, {
    cwd: webRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe']
  }).trim();

  const revision = git('rev-parse', '--short=7', 'HEAD');
  dirty = git('status', '--porcelain', '--untracked-files=normal').length > 0;
  commit = revision;
} catch {
  console.warn('[version] Git metadata unavailable; using unknown commit.');
}

// Generate once per build. The running app reads this constant, including offline.
const builtAt = new Date().toISOString();
const revision = `${commit}${dirty ? '-dirty' : ''}`;
const appVersion = {
  version,
  commit,
  dirty,
  builtAt,
  buildId: `${revision}-${builtAt.replace(/[-:.]/g, '')}`
};

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(new URL('app-version.ts', outputDirectory),
  '// Generated by scripts/generate-app-version.mjs. Do not edit manually.\n' +
  `export const APP_VERSION = ${JSON.stringify(appVersion, null, 2)} as const;\n`);

console.log(`[version] ${version} · ${appVersion.buildId}`);
